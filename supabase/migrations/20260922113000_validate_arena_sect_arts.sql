create or replace function private.server_sect_art_bonus(p_user uuid,p_channel text)
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare c private.player_cave_states;r record;base_value numeric;direct_value numeric;total_value numeric;root_level integer;element_pct numeric;tq numeric:=0;rb numeric:=0;ph numeric:=0;ag numeric:=0;sp numeric:=0;
begin
 select * into c from private.player_cave_states where user_id=p_user and channel=p_channel;
 for r in select a.level,a.sect_star,s.kind,s.element from private.player_sect_arts a join private.sect_art_catalog s on s.sect_name=a.sect_name and s.slot=a.slot where a.user_id=p_user and a.channel=p_channel and s.kind<>'sectSkill' loop
  base_value:=round((array[120,260,520,900,1400,2050,2933,3352,4800])[r.sect_star]*r.level/10.0);root_level:=case r.element when 'metal' then c.metal_root when 'wood' then c.wood_root when 'water' then c.water_root when 'fire' then c.fire_root else c.earth_root end;direct_value:=base_value+round(base_value*private.spirit_root_bonus(root_level)/100.0);
  select coalesce(sum((x.value->>'value')::numeric),0) into element_pct from private.player_equipment_items i cross join lateral jsonb_array_elements(i.affixes)x where i.user_id=p_user and i.channel=p_channel and i.equipped and i.slot in('pendant','ring') and x.value->>'element'=case r.element when 'metal' then '金' when 'wood' then '木' when 'water' then '水' when 'fire' then '火' else '土' end;
  total_value:=round(direct_value*(1+element_pct/100.0));if r.kind='secret' then tq:=tq+total_value;elsif r.kind='formula' then rb:=rb+total_value;elsif r.kind='sutra' then ph:=ph+total_value;elsif r.kind='escape' then ag:=ag+total_value;elsif r.kind='ultimate' then sp:=sp+round(total_value*.25);end if;
 end loop;return jsonb_build_object('trueQi',tq,'rootBone',rb,'physique',ph,'agility',ag,'spiritualPower',sp);
end $$;

alter function private.arena_validate_server_progression(uuid,text,jsonb) rename to arena_validate_server_progression_book_arts;
create or replace function private.arena_validate_server_progression(p_user uuid,p_channel text,p_snapshot jsonb) returns void language plpgsql stable security definer set search_path='' as $$declare expected jsonb;book_bonus jsonb;sect_bonus jsonb;provided jsonb;k text;begin perform private.arena_validate_server_progression_book_arts(p_user,p_channel,p_snapshot);expected:=private.server_component_core(p_user,p_channel);book_bonus:=private.server_book_art_bonus(p_user,p_channel);sect_bonus:=private.server_sect_art_bonus(p_user,p_channel);provided:=p_snapshot->'sect_core';if jsonb_typeof(provided)<>'object' then raise exception '戰鬥快照缺少伺服器門派功法屬性';end if;foreach k in array array['trueQi','rootBone','physique','agility','spiritualPower'] loop if coalesce((provided->>k)::numeric,-1)<>coalesce((expected->>k)::numeric,0)+coalesce((book_bonus->>k)::numeric,0)+coalesce((sect_bonus->>k)::numeric,0) then raise exception '門派功法屬性與伺服器紀錄不一致';end if;end loop;end $$;

